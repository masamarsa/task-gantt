# Equinox estimates from the National Astronomical Observatory of Japan.
# Values are the days of March and September, beginning with 2028.
# https://www.nao.ac.jp/faq/a0301.html
_EQUINOX_ESTIMATES = (
    (20, 22), (20, 23), (20, 23), (21, 23),
    (20, 22), (20, 23), (20, 23), (21, 23),
    (20, 22), (20, 23), (20, 23), (21, 23),
    (20, 22), (20, 23), (20, 23), (21, 23),
    (20, 22), (20, 22), (20, 23), (21, 23),
    (20, 22), (20, 22), (20, 23),
)
_ONE_DAY = timedelta(days=1)


def _monday(year: int, month: int, occurrence: int) -> date:
    first = date(year, month, 1)
    return date(year, month, 1 + (-first.weekday()) % 7 + (occurrence - 1) * 7)


def _early_holidays(year: int) -> frozenset[date]:
    # The original holiday law took effect on July 20, 1948.
    # These years preceded substitute and citizens' holidays.
    remaining_1948 = ((9, 23), (11, 3), (11, 23))
    if year == 1948:
        dates = remaining_1948
    else:
        autumn = 24 if year == 1951 else 23
        dates = ((1, 1), (1, 15), (3, 21), (4, 29), (5, 3), (5, 5),
                 (9, autumn), (11, 3), (11, 23))
    return frozenset(date(year, month, day) for month, day in dates)


def _projected_holidays(year: int) -> frozenset[date]:
    statutory = {
        date(year, 1, 1), _monday(year, 1, 2), date(year, 2, 11), date(year, 2, 23),
        date(year, 4, 29), date(year, 5, 3), date(year, 5, 4), date(year, 5, 5),
        _monday(year, 7, 3), date(year, 8, 11), _monday(year, 9, 3),
        _monday(year, 10, 2), date(year, 11, 3), date(year, 11, 23),
    }
    offset = year - 2028
    if 0 <= offset < len(_EQUINOX_ESTIMATES):
        spring, autumn = _EQUINOX_ESTIMATES[offset]
        statutory.update((date(year, 3, spring), date(year, 9, autumn)))

    holidays = set(statutory)
    for holiday in statutory:
        following = holiday + _ONE_DAY
        # A day between two statutory holidays is a citizens' holiday.
        if following not in statutory and following + _ONE_DAY in statutory:
            holidays.add(following)
        if holiday.weekday() == 6:
            # A Sunday holiday is observed on the next non-statutory date.
            while following in statutory:
                following += _ONE_DAY
            holidays.add(following)
    return frozenset(holidays)


@lru_cache(maxsize=128)
def public_holidays(year: int) -> frozenset[date]:
    """Return holiday dates under Japan's post-1948 public holiday law.

    The Cabinet Office snapshot covers 1955–2027. Later dates use the law as
    published, with equinox estimates through 2050. Further years include
    fixed-date and weekday-based holidays.
    """
    if year < 1948:
        return frozenset()
    if year < 1955:
        return _early_holidays(year)
    if year in _PUBLISHED_DATES:
        return frozenset(date.fromisoformat(f"{year}-{value}") for value in _PUBLISHED_DATES[year].split())
    return _projected_holidays(year)


def is_public_holiday(day: date) -> bool:
    return day in public_holidays(day.year)
